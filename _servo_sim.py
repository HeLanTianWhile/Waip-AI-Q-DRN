"""数值仿真光标伺服，选定增益 K 与每键移动 tick 数 M，确保点击前落入按键范围。"""
import math

# 按键坐标（来自离屏测量）
KEYS = {
 'q':(22,694),'w':(60,694),'e':(99,694),'r':(137,694),'t':(176,694),'y':(214,694),
 'u':(253,694),'i':(291,694),'o':(330,694),'p':(368,694),
 'a':(24,735),'s':(67,735),'d':(109,735),'f':(152,735),'g':(195,735),'h':(238,735),
 'j':(281,735),'k':(323,735),'l':(366,735),
 'z':(67,776),'x':(109,776),'c':(152,776),'v':(195,776),'b':(238,776),'n':(281,776),
 'm':(323,776),
 '，':(32,817),'空格':(141,817),'？':(250,817),'Enter':(333,817),
 'send':(355,646),
}
# 按键命中矩形（容差：键宽的一半，取保守 14px）
KEY_RECT = {  # half-width, half-height
 'q':(17,18),'w':(17,18),'e':(17,18),'r':(17,18),'t':(17,18),'y':(17,18),
 'u':(17,18),'i':(17,18),'o':(17,18),'p':(17,18),
 'a':(19,18),'s':(19,18),'d':(19,18),'f':(19,18),'g':(19,18),'h':(19,18),
 'j':(19,18),'k':(19,18),'l':(19,18),
 'z':(19,18),'x':(19,18),'c':(19,18),'v':(19,18),'b':(19,18),'n':(19,18),'m':(19,18),
 '，':(26,18),'空格':(77,18),'？':(26,18),'Enter':(52,18),
 'send':(25,17),
}

MSG1 = ['n','i','空格','h','a','o','空格','，','n','i','空格','z','a','i','空格','m','a','空格','？','send']
MSG2 = ['n','i','空格','d','a','o','空格','d','i','空格','z','a','i','空格','b','u','空格','z','a','i','空格','？','send']

def run(K, M, seq, x0=195.0, y0=422.0):
    x,y = x0,y0
    misses=0; log=[]
    for k in seq:
        tx,ty = KEYS[k]
        for _ in range(M):
            x = max(0,min(390, x + 390*math.tanh(K*((tx/390)-(x/390)))))
            y = max(0,min(844, y + 844*math.tanh(K*((ty/844)-(y/844)))))
        hx,hy = KEY_RECT[k]
        ok = (abs(x-tx)<=hx and abs(y-ty)<=hy)
        if not ok: misses+=1
        log.append((k, round(x,1), round(y,1), tx, ty, ok))
    return misses, log

for K in [0.6, 0.8, 1.0, 1.2]:
    for M in [3,4,5,6]:
        m1,_ = run(K,M,MSG1)
        m2,_ = run(K,M,MSG2)
        flag = "OK" if (m1+m2)==0 else ""
        print(f"K={K} M={M}: msg1_miss={m1} msg2_miss={m2} {flag}")
